#!/usr/bin/env python3
"""The shipped pipeline key list (data/native/pipeline_keys.bin).

  tools/native/pipeline_keys.py merge <UserData/native_pipeline_keys.bin>...
      add the keys of players' runs (deduplicated, first-use order kept)
  tools/native/pipeline_keys.py inc
      write src/native/pipeline_keys.inc (the list as bytes, built in)

A key file is a 16-byte header (magic 'NNPK', version, key size, count) and
fixed-size PipelineKeys (src/native/native_draw.cpp): shader hashes, formats
and render-state register values - no shader code and no game data. At start
the renderer queues the built-in keys and the player's own
(native_precompile_pipelines), so even a first run finds its pipelines built.
"""
import pathlib, struct, sys

root = pathlib.Path(__file__).resolve().parents[2]
shipped = root / "data/native/pipeline_keys.bin"
MAGIC = 0x4B504E4E


def read(path):
    d = pathlib.Path(path).read_bytes()
    magic, version, size, count = struct.unpack("<4I", d[:16])
    if magic != MAGIC or len(d) != 16 + size * count:
        raise SystemExit(f"{path}: not a pipeline key file")
    return version, size, [d[16 + i * size:16 + (i + 1) * size] for i in range(count)]


def write(path, version, size, keys):
    pathlib.Path(path).write_bytes(struct.pack("<4I", MAGIC, version, size, len(keys)) + b"".join(keys))


if sys.argv[1:2] == ["merge"]:
    version, size, keys = read(shipped) if shipped.exists() else (None, None, [])
    seen = set(keys)
    for p in sys.argv[2:]:
        v, s, more = read(p)
        if version is None:
            version, size = v, s
        if (v, s) != (version, size):
            print(f"{p}: key version {v}/{s} differs from {version}/{size}: skipped")
            continue
        new = [k for k in more if k not in seen]
        seen.update(new)
        keys += new
        print(f"{p}: {len(new)} new keys")
    write(shipped, version, size, keys)
    print(f"{shipped.relative_to(root)}: {len(keys)} keys")
elif sys.argv[1:2] == ["inc"]:
    data = shipped.read_bytes()
    lines = [", ".join(f"0x{b:02X}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    out = root / "src/native/pipeline_keys.inc"
    out.write_text("// Generated by tools/native/pipeline_keys.py inc from data/native/pipeline_keys.bin.\n" +
                   ",\n".join(lines) + "\n")
    print(f"{out.relative_to(root)}: {len(data)} bytes")
else:
    print(__doc__)
