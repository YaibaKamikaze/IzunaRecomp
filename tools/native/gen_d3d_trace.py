"""[native renderer, M0] Generate the Direct3D call tracer's hooks.

    python3 tools/native/gen_d3d_trace.py

Reads the public Direct3D functions (docs/native/d3d_public.txt, from
d3d_map.py: the functions the game calls from outside the library block) and
the names known so far (config/d3d_functions.toml), and writes:

  config/hooks/d3d_trace.toml   a midasm hook on each function's first
                                instruction, passing r3-r8
  src/native/d3d_trace_hooks.inc one C++ hook per function, calling
                                ng2native::TraceD3DCall(index, r3..r8)
  src/native/d3d_trace_table.inc the index -> (address, name) table
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def main():
    names = {}
    for line in open(os.path.join(ROOT, "config", "d3d_functions.toml")):
        m = re.match(r'0x([0-9A-Fa-f]{8}) = \{ name = "([^"]+)"', line)
        if m:
            names[int(m.group(1), 16)] = m.group(2)
    addrs = []
    for line in open(os.path.join(ROOT, "docs", "native", "d3d_public.txt")):
        m = re.match(r"([0-9A-F]{8}) \|", line)
        if m:
            addrs.append(int(m.group(1), 16))
    addrs.sort()

    toml = ["# [native renderer, M0] GENERATED by tools/native/gen_d3d_trace.py - do not edit.",
            "# A hook on the first instruction of each public Direct3D function: the",
            "# tracer (src/native/d3d_trace.cpp) counts calls and samples arguments.", ""]
    hooks = ["// GENERATED by tools/native/gen_d3d_trace.py - do not edit."]
    table = ["// GENERATED by tools/native/gen_d3d_trace.py - do not edit."]
    for i, a in enumerate(addrs):
        name = names.get(a, f"d3d_{a:08X}")
        toml += ["[[midasm_hook]]", f"address = 0x{a:08X}", f'name = "ng2NativeTrace{i:03d}"',
                 'registers = ["r3", "r4", "r5", "r6", "r7", "r8"]', "after_instruction = false", ""]
        hooks.append(f"void ng2NativeTrace{i:03d}(PPCRegister& r3, PPCRegister& r4, PPCRegister& r5, "
                     f"PPCRegister& r6, PPCRegister& r7, PPCRegister& r8) "
                     f"{{ ng2native::TraceD3DCall({i}, r3.u32, r4.u32, r5.u32, r6.u32, r7.u32, r8.u32); }}")
        table.append(f'  {{0x{a:08X}u, "{name}"}},')
    open(os.path.join(ROOT, "config", "hooks", "d3d_trace.toml"), "w").write("\n".join(toml))
    os.makedirs(os.path.join(ROOT, "src", "native"), exist_ok=True)
    open(os.path.join(ROOT, "src", "native", "d3d_trace_hooks.inc"), "w").write("\n".join(hooks) + "\n")
    open(os.path.join(ROOT, "src", "native", "d3d_trace_table.inc"), "w").write("\n".join(table) + "\n")
    print(f"{len(addrs)} functions, {sum(a in names for a in addrs)} named")


if __name__ == "__main__":
    main()
