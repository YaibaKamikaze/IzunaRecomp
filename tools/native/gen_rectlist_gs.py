#!/usr/bin/env python3
"""Generate the rect-list geometry shader (src/native/shaders/rectlist.geom ->
src/native/shaders/rectlist_gs.inc, SPIR-V words).

A Xenos rectangle list gives three corners of each rectangle; the hardware
makes the fourth. The geometry shader finds the right-angle corner c of the
triangle (in screen space), computes d = a + b - c for the position and all
16 interpolants (the translated vertex shaders write TEXCOORD0-15 at
locations 0-15), and emits the strip c, a, b, d - as Xenia does.

  tools/native/gen_rectlist_gs.py   (needs glslangValidator)
"""
import pathlib, subprocess, struct, tempfile

N = 16
lines = ["#version 450", "layout(triangles) in;", "layout(triangle_strip, max_vertices = 4) out;"]
lines += [f"layout(location = {i}) in vec4 i{i}[];" for i in range(N)]
lines += [f"layout(location = {i}) out vec4 o{i};" for i in range(N)]
lines += ["void emit(int k) {", "  gl_Position = gl_in[k].gl_Position;"]
lines += [f"  o{i} = i{i}[k];" for i in range(N)]
lines += ["  EmitVertex();", "}"]
lines += ["void main() {",
          "  vec2 p[3];",
          "  for (int k = 0; k < 3; ++k) p[k] = gl_in[k].gl_Position.xy / gl_in[k].gl_Position.w;",
          "  // the corner whose two edges are the most perpendicular",
          "  int c = 0; float best = 1e30;",
          "  for (int k = 0; k < 3; ++k) {",
          "    vec2 e1 = p[(k + 1) % 3] - p[k], e2 = p[(k + 2) % 3] - p[k];",
          "    float d = abs(dot(e1, e2)) / max(length(e1) * length(e2), 1e-20);",
          "    if (d < best) { best = d; c = k; }",
          "  }",
          "  int a = (c + 1) % 3, b = (c + 2) % 3;",
          "  emit(c); emit(a); emit(b);",
          "  gl_Position = gl_in[a].gl_Position + gl_in[b].gl_Position - gl_in[c].gl_Position;"]
lines += [f"  o{i} = i{i}[a] + i{i}[b] - i{i}[c];" for i in range(N)]
lines += ["  EmitVertex();", "  EndPrimitive();", "}"]
root = pathlib.Path(__file__).resolve().parents[2]
src = root / "src/native/shaders/rectlist.geom"
src.write_text("// GENERATED by tools/native/gen_rectlist_gs.py - do not edit.\n" + "\n".join(lines) + "\n")
with tempfile.TemporaryDirectory() as t:
    out = pathlib.Path(t) / "rect.spv"
    subprocess.run(["glslangValidator", "-V", "--target-env", "vulkan1.1", str(src), "-o", str(out)], check=True,
                   stdout=subprocess.DEVNULL)
    words = struct.unpack(f"<{out.stat().st_size // 4}I", out.read_bytes())
inc = root / "src/native/shaders/rectlist_gs.inc"
inc.write_text("// GENERATED by tools/native/gen_rectlist_gs.py from rectlist.geom - do not edit.\n" +
               ",\n".join(", ".join(f"0x{w:08X}" for w in words[i:i + 8]) for i in range(0, len(words), 8)) + "\n")
print(inc, len(words), "words")
