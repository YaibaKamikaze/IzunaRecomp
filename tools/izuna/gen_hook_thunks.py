#!/usr/bin/env python3
"""Make every recompiled game function hookable at runtime (src/izuna/izuna_hooks.h).

    tools/izuna/gen_hook_thunks.py [generated/default]

Each game function is defined by the codegen as a weak symbol, an alias of
its body __imp__<name> (DEFINE_REX_FUNC). This writes a strong <name> for each
one - a thunk that calls the body straight away unless a hook is set on it:

    if (izuna_hook_flags[i]) return IzunaHookDispatch(i, ctx, base, __imp__<name>);
    [[clang::musttail]] return __imp__<name>(ctx, base);

so every call of a game function (direct, or indirect through the codegen's
function table) can be hooked, at the cost of one byte read and a branch.
Written to generated/default/izuna_hooks.<n>.cpp (derived from the game: not in
the repo). Run after every codegen (CLAUDE.md, the codegen steps).
"""
import os
import re
import sys

PARTS = 16


def main():
    gen = sys.argv[1] if len(sys.argv) > 1 else "generated/default"
    names = []
    for f in sorted(os.listdir(gen)):
        if re.fullmatch(r"ng2_recomp\.\d+\.cpp", f):
            names += re.findall(r"^DEFINE_REX_FUNC\((\w+)\)", open(os.path.join(gen, f)).read(), re.M)
    mapping = dict((n, int(a, 16)) for a, n in
                   re.findall(r"\{ 0x([0-9A-Fa-f]+), (\w+) \}", open(os.path.join(gen, "ng2_init.cpp")).read()))
    funcs = sorted((mapping[n], n) for n in set(names) if n in mapping)
    if not funcs:
        sys.exit(f"{gen}: no functions found - run the codegen first")
    for old in os.listdir(gen):
        if re.fullmatch(r"izuna_hooks\.\d+\.cpp", old):
            os.remove(os.path.join(gen, old))
    head = ("// Generated by tools/izuna/gen_hook_thunks.py - do not edit.\n"
            "#include <cstdint>\n#include <rex/ppc/context.h>\n"
            "extern \"C\" uint8_t izuna_hook_flags[];\n"
            "extern \"C\" void IzunaHookDispatch(uint32_t, PPCContext&, uint8_t*, void (*)(PPCContext&, uint8_t*));\n")
    per = (len(funcs) + PARTS - 1) // PARTS
    for p in range(PARTS):
        out = [head]
        for i in range(p * per, min(len(funcs), (p + 1) * per)):
            name = funcs[i][1]
            out.append(
                f'extern "C" void __imp__{name}(PPCContext& __restrict, uint8_t*);\n'
                f'extern "C" __attribute__((noinline)) void {name}(PPCContext& __restrict ctx, uint8_t* base) {{\n'
                f'  if (__builtin_expect(__atomic_load_n(&izuna_hook_flags[{i}], __ATOMIC_RELAXED), 0))\n'
                f'    return IzunaHookDispatch({i}, ctx, base, __imp__{name});\n'
                f'  [[clang::musttail]] return __imp__{name}(ctx, base);\n}}\n')
        if p == 0:
            out.append(f'extern "C" uint8_t izuna_hook_flags[{len(funcs)}] = {{}};\n')
            out.append(f'extern "C" const uint32_t izuna_hook_count = {len(funcs)};\n')
            out.append(f'extern "C" const uint32_t izuna_hook_addresses[{len(funcs)}] = {{\n')
            for k in range(0, len(funcs), 8):
                out.append("  " + ", ".join(f"0x{a:08X}" for a, _ in funcs[k:k + 8]) + ",\n")
            out.append("};\n")
        with open(os.path.join(gen, f"izuna_hooks.{p}.cpp"), "w") as f:
            f.write("".join(out))
    print(f"{len(funcs)} game functions made hookable ({PARTS} files)")


if __name__ == "__main__":
    main()
